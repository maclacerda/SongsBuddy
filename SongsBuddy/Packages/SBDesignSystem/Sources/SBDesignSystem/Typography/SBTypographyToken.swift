import Foundation

/// Defines the typography tokens used across the SongsBuddy design system.
public enum SBTypographyToken: Sendable {
    /// Display style with 16pt size.
    case display16

    /// Display style with 18pt size.
    case display18

    /// Display style with 20pt size.
    case display20

    /// Display style with 24pt size (large titles).
    case display24

    /// Display style with 32pt size (player title).
    case display32

    /// Text style with 12pt size (secondary labels).
    case text12

    /// Text style with 14pt size.
    case text14

    /// Text style with 16pt size (primary content).
    case text16
}
